namespace {
class NDS32MCCodeEmitter : public MCCodeEmitter {
  const MCInstrInfo &MCII;
  const MCRegisterInfo &MRI;

public:
  NDS32MCCodeEmitter(const MCInstrInfo &MCII, const MCRegisterInfo &MRI)
      : MCII(MCII), MRI(MRI) {}

  void encodeInstruction(const MCInst &MI, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // Generated by -gen-emitter from the TableGen Inst{} fields. Returns 0 for
  // instructions not yet migrated (no Inst{} bits set).
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;
  // Default operand encoder used by the generated code.
  unsigned getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

  // OpNo-based operand EncoderMethods for the generated encoder. They wrap the
  // existing helpers so both the hand-written switch and the TableGen encoder
  // share the same encoding logic during the migration.
  unsigned encodeImm15(const MCInst &MI, unsigned OpNo,
                       SmallVectorImpl<MCFixup> &Fixups,
                       const MCSubtargetInfo &STI) const {
    return getImm16(MI, MI.getOperand(OpNo), Fixups, STI);
  }
  unsigned encodeImm20(const MCInst &MI, unsigned OpNo,
                       SmallVectorImpl<MCFixup> &Fixups,
                       const MCSubtargetInfo &STI) const {
    return getImm20(MI, MI.getOperand(OpNo), Fixups, STI);
  }
  // Memory operands occupy Inst[19:0]: base register in [19:15], scaled offset
  // in [14:0].
  unsigned encodeMemWords(const MCInst &MI, unsigned OpNo,
                          SmallVectorImpl<MCFixup> &Fixups,
                          const MCSubtargetInfo &STI) const {
    return (getReg(MI.getOperand(OpNo)) << 15) |
           getMemOffsetWords(MI, MI.getOperand(OpNo + 1), Fixups, STI);
  }
  unsigned encodeMemBytes(const MCInst &MI, unsigned OpNo,
                          SmallVectorImpl<MCFixup> &Fixups,
                          const MCSubtargetInfo &STI) const {
    return (getReg(MI.getOperand(OpNo)) << 15) |
           getMemOffsetBytes(MI.getOperand(OpNo + 1));
  }
  unsigned encodeMemHalfwords(const MCInst &MI, unsigned OpNo,
                              SmallVectorImpl<MCFixup> &Fixups,
                              const MCSubtargetInfo &STI) const {
    return (getReg(MI.getOperand(OpNo)) << 15) |
           getMemOffsetHalfwords(MI.getOperand(OpNo + 1));
  }
  unsigned encodeBr25(const MCInst &MI, unsigned OpNo,
                      SmallVectorImpl<MCFixup> &Fixups,
                      const MCSubtargetInfo &STI) const {
    return encodeBranchTarget(MI.getOperand(OpNo), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_25_pcrel));
  }
  unsigned encodeBr17(const MCInst &MI, unsigned OpNo,
                      SmallVectorImpl<MCFixup> &Fixups,
                      const MCSubtargetInfo &STI) const {
    return encodeBranchTarget(MI.getOperand(OpNo), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_17_pcrel));
  }
  unsigned encodeBr15(const MCInst &MI, unsigned OpNo,
                      SmallVectorImpl<MCFixup> &Fixups,
                      const MCSubtargetInfo &STI) const {
    return encodeBranchTarget(MI.getOperand(OpNo), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_15_pcrel));
  }
  // 16-bit short-branch target: 8-bit PC-relative displacement field (scaled by
  // 2). A symbolic target emits a fixup_nds32_9_pcrel (which relaxation grows to
  // a 32-bit branch if out of range, so it seldom survives to the object).
  unsigned encodeBr9(const MCInst &MI, unsigned OpNo,
                     SmallVectorImpl<MCFixup> &Fixups,
                     const MCSubtargetInfo &STI) const {
    const MCOperand &Op = MI.getOperand(OpNo);
    if (Op.isImm())
      return (static_cast<uint32_t>(Op.getImm()) >> 1) & 0xff;
    assert(Op.isExpr() && "expected branch target expression");
    Fixups.push_back(MCFixup::create(
        0, Op.getExpr(), static_cast<MCFixupKind>(NDS32::fixup_nds32_9_pcrel),
        /*PCRel=*/true));
    return 0;
  }
  // 16-bit add45/addi45 4-bit register field: r0-r11 -> 0-11, r16-r19 -> 12-15.
  unsigned encodeGPR4(const MCInst &MI, unsigned OpNo,
                      SmallVectorImpl<MCFixup> &Fixups,
                      const MCSubtargetInfo &STI) const {
    unsigned Hw = MRI.getEncodingValue(MI.getOperand(OpNo).getReg());
    assert((Hw <= 11 || (Hw >= 16 && Hw <= 19)) &&
           "register not encodable in add45/addi45 4-bit field");
    return Hw <= 11 ? Hw : Hw - 4;
  }
  // gp-relative lwi.gp/swi.gp: signed 17-bit WORD offset in Inst[16:0]. The
  // operand carries a byte displacement (matching what decodeOff17Words prints),
  // so scale it here; the two directions would otherwise disagree by four.
  unsigned encodeOff17Words(const MCInst &MI, unsigned OpNo,
                            SmallVectorImpl<MCFixup> &Fixups,
                            const MCSubtargetInfo &STI) const {
    int64_t Byte = MI.getOperand(OpNo).getImm();
    assert(Byte % 4 == 0 && "gp-relative word offset must be 4-byte aligned");
    assert(isInt<17>(Byte / 4) && "gp-relative offset out of 17-bit word range");
    return static_cast<uint32_t>(Byte >> 2) & 0x1ffff;
  }
  // gp-relative halfword ops: the operand is a byte displacement, the field
  // holds it in halfwords. Same split as encodeOff17Words.
  unsigned encodeOff18Halfwords(const MCInst &MI, unsigned OpNo,
                                SmallVectorImpl<MCFixup> &Fixups,
                                const MCSubtargetInfo &STI) const {
    int64_t Byte = MI.getOperand(OpNo).getImm();
    assert(Byte % 2 == 0 && "gp-relative halfword offset must be 2-byte aligned");
    assert(isInt<18>(Byte / 2) && "gp-relative offset out of 18-bit range");
    return static_cast<uint32_t>(Byte >> 1) & 0x3ffff;
  }
  // 16-bit sp-/fp-relative word offsets: byte displacement in, word count out.
  unsigned encodeOff7Words(const MCInst &MI, unsigned OpNo,
                           SmallVectorImpl<MCFixup> &Fixups,
                           const MCSubtargetInfo &STI) const {
    return (static_cast<uint32_t>(MI.getOperand(OpNo).getImm()) >> 2) & 0x7f;
  }
  unsigned encodeOff6Words(const MCInst &MI, unsigned OpNo,
                           SmallVectorImpl<MCFixup> &Fixups,
                           const MCSubtargetInfo &STI) const {
    return (static_cast<uint32_t>(MI.getOperand(OpNo).getImm()) >> 2) & 0x3f;
  }
  // 16-bit lwi333/swi333: 3-bit word offset.
  unsigned encodeOff3Words(const MCInst &MI, unsigned OpNo,
                           SmallVectorImpl<MCFixup> &Fixups,
                           const MCSubtargetInfo &STI) const {
    return (static_cast<uint32_t>(MI.getOperand(OpNo).getImm()) >> 2) & 0x7;
  }
  // Register-offset memory: base[19:15] + index[14:10] + scale[9:8] packed into
  // the 12-bit field Inst[19:8].
  unsigned encodeRegOffset(const MCInst &MI, unsigned OpNo,
                           SmallVectorImpl<MCFixup> &Fixups,
                           const MCSubtargetInfo &STI) const {
    return (getReg(MI.getOperand(OpNo)) << 7) |
           (getReg(MI.getOperand(OpNo + 1)) << 2) |
           (static_cast<uint32_t>(MI.getOperand(OpNo + 2).getImm()) & 0x3);
  }
  // Post-increment immediate: byte increment scaled to element units (15-bit).
  template <unsigned Shift>
  unsigned encodePostInc(const MCInst &MI, unsigned OpNo,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const {
    return (static_cast<uint32_t>(MI.getOperand(OpNo).getImm()) >> Shift) &
           0x7fff;
  }
  unsigned encodePostByte(const MCInst &MI, unsigned OpNo,
                          SmallVectorImpl<MCFixup> &F,
                          const MCSubtargetInfo &S) const {
    return encodePostInc<0>(MI, OpNo, F, S);
  }
  unsigned encodePostHalf(const MCInst &MI, unsigned OpNo,
                          SmallVectorImpl<MCFixup> &F,
                          const MCSubtargetInfo &S) const {
    return encodePostInc<1>(MI, OpNo, F, S);
  }
  unsigned encodePostWord(const MCInst &MI, unsigned OpNo,
                          SmallVectorImpl<MCFixup> &F,
                          const MCSubtargetInfo &S) const {
    return encodePostInc<2>(MI, OpNo, F, S);
  }

private:
  uint32_t getReg(const MCOperand &Op) const;
  uint32_t getImm16(const MCInst &MI, const MCOperand &Op,
                    SmallVectorImpl<MCFixup> &Fixups,
                    const MCSubtargetInfo &STI) const;
  uint32_t getImm20(const MCInst &MI, const MCOperand &Op,
                    SmallVectorImpl<MCFixup> &Fixups,
                    const MCSubtargetInfo &STI) const;
  uint32_t getMemOffsetWords(const MCInst &MI, const MCOperand &Op,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;
  uint32_t getMemOffsetBytes(const MCOperand &Op) const;
  uint32_t getMemOffsetHalfwords(const MCOperand &Op) const;
  uint32_t encodeBranchTarget(const MCOperand &Op, SmallVectorImpl<MCFixup> &Fixups,
                              MCFixupKind Kind) const;
};
} // namespace

uint32_t NDS32MCCodeEmitter::getReg(const MCOperand &Op) const {
  assert(Op.isReg() && "expected register operand");
  return MRI.getEncodingValue(Op.getReg());
}

// Default operand encoder for the generated getBinaryCodeForInstr: registers
// contribute their hardware encoding, plain immediates their value. Operands
// needing scaling/fixups use a dedicated EncoderMethod instead.
unsigned NDS32MCCodeEmitter::getMachineOpValue(const MCInst &MI,
                                               const MCOperand &MO,
                                               SmallVectorImpl<MCFixup> &Fixups,
                                               const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return MRI.getEncodingValue(MO.getReg());
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm());
  return 0;
}

#include "NDS32GenMCCodeEmitter.inc"

uint32_t NDS32MCCodeEmitter::getImm16(const MCInst &MI, const MCOperand &Op,
                                      SmallVectorImpl<MCFixup> &Fixups,
                                      const MCSubtargetInfo &STI) const {
  if (Op.isImm())
    // The I-type immediate field is 15 bits ([14:0]); masking 16 bits would
    // leak bit 15 of a negative immediate into the $ra field.
    return static_cast<uint32_t>(Op.getImm()) & 0x7fff;

  assert(Op.isExpr() && "expected immediate or expression operand");
  MCFixupKind Kind = MCFixupKind(0);
  if (const auto *SE = dyn_cast<MCSpecifierExpr>(Op.getExpr())) {
    switch (SE->getSpecifier()) {
    case NDS32::S_HI20:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_hi20);
      break;
    case NDS32::S_LO12S0:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_lo12s0);
      break;
    case NDS32::S_LO12S2:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_lo12s2);
      break;
    case NDS32::S_GOTOFF_LO12:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_gotoff_lo12);
      break;
    case NDS32::S_GOT_LO12:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_got_lo12);
      break;
    case NDS32::S_TLS_LE_LO12:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_tls_le_lo12);
      break;
    default:
      llvm_unreachable("unsupported NDS32 specifier");
    }
  }
  if (Kind != 0) {
    Fixups.push_back(MCFixup::create(0, Op.getExpr(), Kind));
  }
  return 0;
}

uint32_t NDS32MCCodeEmitter::getImm20(const MCInst &MI, const MCOperand &Op,
                                      SmallVectorImpl<MCFixup> &Fixups,
                                      const MCSubtargetInfo &STI) const {
  if (Op.isImm())
    return static_cast<uint32_t>(Op.getImm()) & 0xfffff;

  assert(Op.isExpr() && "expected immediate or expression operand");
  MCFixupKind Kind = MCFixupKind(0);
  if (const auto *SE = dyn_cast<MCSpecifierExpr>(Op.getExpr())) {
    switch (SE->getSpecifier()) {
    case NDS32::S_HI20:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_hi20);
      break;
    case NDS32::S_GOTOFF_HI20:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_gotoff_hi20);
      break;
    case NDS32::S_GOT_HI20:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_got_hi20);
      break;
    case NDS32::S_TLS_LE_HI20:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_tls_le_hi20);
      break;
    default:
      break;
    }
  }
  if (Kind != 0) {
    Fixups.push_back(MCFixup::create(0, Op.getExpr(), Kind));
  }
  return 0;
}

uint32_t NDS32MCCodeEmitter::getMemOffsetWords(const MCInst &MI, const MCOperand &Op,
                                               SmallVectorImpl<MCFixup> &Fixups,
                                               const MCSubtargetInfo &STI) const {
  if (Op.isImm()) {
    int64_t Offset = Op.getImm();
    if (Offset % 4 != 0)
      report_fatal_error("NDS32 lwi/swi offset must be word aligned");
    return static_cast<uint32_t>(Offset / 4) & 0x7fff;
  }

  assert(Op.isExpr() && "expected immediate or expression operand");
  MCFixupKind Kind = MCFixupKind(0);
  if (const auto *SE = dyn_cast<MCSpecifierExpr>(Op.getExpr())) {
    if (SE->getSpecifier() == NDS32::S_LO12S2)
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_lo12s2);
  }
  if (Kind != 0) {
    Fixups.push_back(MCFixup::create(0, Op.getExpr(), Kind));
  }
  return 0;
}

uint32_t NDS32MCCodeEmitter::getMemOffsetBytes(const MCOperand &Op) const {
  if (!Op.isImm())
    report_fatal_error("NDS32 byte memory offset must be an immediate");
  return static_cast<uint32_t>(Op.getImm()) & 0x7fff;
}

uint32_t NDS32MCCodeEmitter::getMemOffsetHalfwords(const MCOperand &Op) const {
  if (!Op.isImm())
    report_fatal_error("NDS32 halfword memory offset must be an immediate");
  int64_t Offset = Op.getImm();
  if (Offset % 2 != 0)
    report_fatal_error("NDS32 lhi/lhsi/shi offset must be halfword aligned");
  return static_cast<uint32_t>(Offset / 2) & 0x7fff;
}

uint32_t NDS32MCCodeEmitter::encodeBranchTarget(
    const MCOperand &Op, SmallVectorImpl<MCFixup> &Fixups,
    MCFixupKind Kind) const {
  if (Op.isImm())
    return static_cast<uint32_t>(Op.getImm() / 2);

  assert(Op.isExpr() && "expected branch target expression");
  // Branch fixups are PC-relative; in LLVM 22 this is carried per-fixup so the
  // MC layer computes the displacement relative to the fixup location.
  Fixups.push_back(MCFixup::create(0, Op.getExpr(), Kind, /*PCRel=*/true));
  return 0;
}

void NDS32MCCodeEmitter::encodeInstruction(
    const MCInst &MI, SmallVectorImpl<char> &CB, SmallVectorImpl<MCFixup> &Fixups,
    const MCSubtargetInfo &STI) const {
  // Encode via the TableGen-generated encoder (from the Inst{} fields).
  uint64_t Bits = getBinaryCodeForInstr(MI, Fixups, STI);
  unsigned Size = MCII.get(MI.getOpcode()).getSize();

  // NDS32 instructions are always big-endian, independent of the data
  // endianness selected by the triple (the Andes toolchain emits identical
  // .text for -EB and -EL; only data is byte-swapped). Always write big-endian.
  raw_svector_ostream OS(CB);
  support::endian::Writer Writer(OS, llvm::endianness::big);
  if (Size == 2)
    Writer.write<uint16_t>(static_cast<uint16_t>(Bits));
  else
    Writer.write<uint32_t>(Bits);
}

MCCodeEmitter *llvm::createNDS32MCCodeEmitter(const MCInstrInfo &MCII,
                                              MCContext &Ctx) {
  return new NDS32MCCodeEmitter(MCII, *Ctx.getRegisterInfo());
}
