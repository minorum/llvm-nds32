namespace {
class NDS32MCCodeEmitter : public MCCodeEmitter {
  const MCRegisterInfo &MRI;
  bool IsLittleEndian;

public:
  NDS32MCCodeEmitter(const MCRegisterInfo &MRI, bool IsLittleEndian)
      : MRI(MRI), IsLittleEndian(IsLittleEndian) {}

  void encodeInstruction(const MCInst &MI, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // Generated by -gen-emitter from the TableGen Inst{} fields. Returns 0 for
  // instructions not yet migrated (no Inst{} bits set).
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;
  // Default operand encoder used by the generated code.
  unsigned getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

private:
  uint32_t getReg(const MCOperand &Op) const;
  uint32_t getImm16(const MCInst &MI, const MCOperand &Op,
                    SmallVectorImpl<MCFixup> &Fixups,
                    const MCSubtargetInfo &STI) const;
  uint32_t getImm20(const MCInst &MI, const MCOperand &Op,
                    SmallVectorImpl<MCFixup> &Fixups,
                    const MCSubtargetInfo &STI) const;
  uint32_t getMemOffsetWords(const MCInst &MI, const MCOperand &Op,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;
  uint32_t getMemOffsetBytes(const MCOperand &Op) const;
  uint32_t getMemOffsetHalfwords(const MCOperand &Op) const;
  uint32_t encodeBranchTarget(const MCOperand &Op, SmallVectorImpl<MCFixup> &Fixups,
                              MCFixupKind Kind) const;
};
} // namespace

uint32_t NDS32MCCodeEmitter::getReg(const MCOperand &Op) const {
  assert(Op.isReg() && "expected register operand");
  return MRI.getEncodingValue(Op.getReg());
}

// Default operand encoder for the generated getBinaryCodeForInstr: registers
// contribute their hardware encoding, plain immediates their value. Operands
// needing scaling/fixups use a dedicated EncoderMethod instead.
unsigned NDS32MCCodeEmitter::getMachineOpValue(const MCInst &MI,
                                               const MCOperand &MO,
                                               SmallVectorImpl<MCFixup> &Fixups,
                                               const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return MRI.getEncodingValue(MO.getReg());
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm());
  return 0;
}

#include "NDS32GenMCCodeEmitter.inc"

uint32_t NDS32MCCodeEmitter::getImm16(const MCInst &MI, const MCOperand &Op,
                                      SmallVectorImpl<MCFixup> &Fixups,
                                      const MCSubtargetInfo &STI) const {
  if (Op.isImm())
    return static_cast<uint32_t>(Op.getImm()) & 0xffff;

  assert(Op.isExpr() && "expected immediate or expression operand");
  MCFixupKind Kind = MCFixupKind(0);
  if (const auto *SE = dyn_cast<MCSpecifierExpr>(Op.getExpr())) {
    switch (SE->getSpecifier()) {
    case NDS32::S_HI20:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_hi20);
      break;
    case NDS32::S_LO12S0:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_lo12s0);
      break;
    case NDS32::S_LO12S2:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_lo12s2);
      break;
    case NDS32::S_GOTOFF_LO12:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_gotoff_lo12);
      break;
    case NDS32::S_GOT_LO12:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_got_lo12);
      break;
    case NDS32::S_TLS_LE_LO12:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_tls_le_lo12);
      break;
    default:
      llvm_unreachable("unsupported NDS32 specifier");
    }
  }
  if (Kind != 0) {
    Fixups.push_back(MCFixup::create(0, Op.getExpr(), Kind));
  }
  return 0;
}

uint32_t NDS32MCCodeEmitter::getImm20(const MCInst &MI, const MCOperand &Op,
                                      SmallVectorImpl<MCFixup> &Fixups,
                                      const MCSubtargetInfo &STI) const {
  if (Op.isImm())
    return static_cast<uint32_t>(Op.getImm()) & 0xfffff;

  assert(Op.isExpr() && "expected immediate or expression operand");
  MCFixupKind Kind = MCFixupKind(0);
  if (const auto *SE = dyn_cast<MCSpecifierExpr>(Op.getExpr())) {
    switch (SE->getSpecifier()) {
    case NDS32::S_HI20:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_hi20);
      break;
    case NDS32::S_GOTOFF_HI20:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_gotoff_hi20);
      break;
    case NDS32::S_GOT_HI20:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_got_hi20);
      break;
    case NDS32::S_TLS_LE_HI20:
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_tls_le_hi20);
      break;
    default:
      break;
    }
  }
  if (Kind != 0) {
    Fixups.push_back(MCFixup::create(0, Op.getExpr(), Kind));
  }
  return 0;
}

uint32_t NDS32MCCodeEmitter::getMemOffsetWords(const MCInst &MI, const MCOperand &Op,
                                               SmallVectorImpl<MCFixup> &Fixups,
                                               const MCSubtargetInfo &STI) const {
  if (Op.isImm()) {
    int64_t Offset = Op.getImm();
    if (Offset % 4 != 0)
      report_fatal_error("NDS32 lwi/swi offset must be word aligned");
    return static_cast<uint32_t>(Offset / 4) & 0x7fff;
  }

  assert(Op.isExpr() && "expected immediate or expression operand");
  MCFixupKind Kind = MCFixupKind(0);
  if (const auto *SE = dyn_cast<MCSpecifierExpr>(Op.getExpr())) {
    if (SE->getSpecifier() == NDS32::S_LO12S2)
      Kind = static_cast<MCFixupKind>(NDS32::fixup_nds32_lo12s2);
  }
  if (Kind != 0) {
    Fixups.push_back(MCFixup::create(0, Op.getExpr(), Kind));
  }
  return 0;
}

uint32_t NDS32MCCodeEmitter::getMemOffsetBytes(const MCOperand &Op) const {
  if (!Op.isImm())
    report_fatal_error("NDS32 byte memory offset must be an immediate");
  return static_cast<uint32_t>(Op.getImm()) & 0x7fff;
}

uint32_t NDS32MCCodeEmitter::getMemOffsetHalfwords(const MCOperand &Op) const {
  if (!Op.isImm())
    report_fatal_error("NDS32 halfword memory offset must be an immediate");
  int64_t Offset = Op.getImm();
  if (Offset % 2 != 0)
    report_fatal_error("NDS32 lhi/lhsi/shi offset must be halfword aligned");
  return static_cast<uint32_t>(Offset / 2) & 0x7fff;
}

uint32_t NDS32MCCodeEmitter::encodeBranchTarget(
    const MCOperand &Op, SmallVectorImpl<MCFixup> &Fixups,
    MCFixupKind Kind) const {
  if (Op.isImm())
    return static_cast<uint32_t>(Op.getImm() / 2);

  assert(Op.isExpr() && "expected branch target expression");
  // Branch fixups are PC-relative; in LLVM 22 this is carried per-fixup so the
  // MC layer computes the displacement relative to the fixup location.
  Fixups.push_back(MCFixup::create(0, Op.getExpr(), Kind, /*PCRel=*/true));
  return 0;
}

void NDS32MCCodeEmitter::encodeInstruction(
    const MCInst &MI, SmallVectorImpl<char> &CB, SmallVectorImpl<MCFixup> &Fixups,
    const MCSubtargetInfo &STI) const {
  uint32_t Bits = 0;
  unsigned Size = 4; // 16-bit forms set this to 2 below.

  switch (MI.getOpcode()) {
  // 16-bit (compressed) forms.
  case NDS32::MOV55:
    Size = 2;
    Bits = 0x8000 | (getReg(MI.getOperand(0)) << 5) | getReg(MI.getOperand(1));
    break;
  case NDS32::MOVI55:
    Size = 2;
    Bits = 0x8400 | (getReg(MI.getOperand(0)) << 5) |
           (static_cast<uint32_t>(MI.getOperand(1).getImm()) & 0x1f);
    break;
  case NDS32::ADD45: // rt(0), src(1,tied), rb(2)
    Size = 2;
    Bits = 0x8800 | (getReg(MI.getOperand(0)) << 5) | getReg(MI.getOperand(2));
    break;
  case NDS32::ADDI45: // rt(0), src(1,tied), imm(2)
    Size = 2;
    Bits = 0x8c00 | (getReg(MI.getOperand(0)) << 5) |
           (static_cast<uint32_t>(MI.getOperand(2).getImm()) & 0x1f);
    break;
  case NDS32::ADDI333:
    Size = 2;
    Bits = 0x9c00 | (getReg(MI.getOperand(0)) << 6) |
           (getReg(MI.getOperand(1)) << 3) |
           (static_cast<uint32_t>(MI.getOperand(2).getImm()) & 0x7);
    break;
  case NDS32::LWI333:
    Size = 2;
    Bits = 0xa000 | (getReg(MI.getOperand(0)) << 6) |
           (getReg(MI.getOperand(1)) << 3) |
           ((static_cast<uint32_t>(MI.getOperand(2).getImm()) >> 2) & 0x7);
    break;
  case NDS32::SWI333:
    Size = 2;
    Bits = 0xa800 | (getReg(MI.getOperand(0)) << 6) |
           (getReg(MI.getOperand(1)) << 3) |
           ((static_cast<uint32_t>(MI.getOperand(2).getImm()) >> 2) & 0x7);
    break;
  case NDS32::NOP:
    Bits = 0x40000009;
    break;
  case NDS32::RET:
    Bits = 0x4a007820;
    break;
  case NDS32::MOVI:
    // movi takes a signed 20-bit immediate (field [19:0]).
    Bits = 0x44000000 | (getReg(MI.getOperand(0)) << 20) |
           getImm20(MI, MI.getOperand(1), Fixups, STI);
    break;
  case NDS32::SETHI:
    Bits = 0x46000000 | (getReg(MI.getOperand(0)) << 20) |
           getImm20(MI, MI.getOperand(1), Fixups, STI);
    break;
  case NDS32::ADDrr:
    Bits = 0x40000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (getReg(MI.getOperand(2)) << 10);
    break;
  case NDS32::ADDri:
    Bits = 0x50000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getImm16(MI, MI.getOperand(2), Fixups, STI);
    break;
  case NDS32::LWI:
    Bits = 0x04000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getMemOffsetWords(MI, MI.getOperand(2), Fixups, STI);
    break;
  case NDS32::LBI:
    Bits = 0x00000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getMemOffsetBytes(MI.getOperand(2));
    break;
  case NDS32::LBSI:
    Bits = 0x20000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getMemOffsetBytes(MI.getOperand(2));
    break;
  case NDS32::LHI:
    Bits = 0x02000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getMemOffsetHalfwords(MI.getOperand(2));
    break;
  case NDS32::LHSI:
    Bits = 0x22000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getMemOffsetHalfwords(MI.getOperand(2));
    break;
  case NDS32::SWI:
    Bits = 0x14000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getMemOffsetWords(MI, MI.getOperand(2), Fixups, STI);
    break;
  case NDS32::SBI:
    Bits = 0x10000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getMemOffsetBytes(MI.getOperand(2));
    break;
  case NDS32::SHI:
    Bits = 0x12000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getMemOffsetHalfwords(MI.getOperand(2));
    break;
  case NDS32::BR:
    Bits = 0x48000000 |
           encodeBranchTarget(MI.getOperand(0), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_25_pcrel));
    break;
  case NDS32::JAL:
    Bits = 0x49000000 |
           encodeBranchTarget(MI.getOperand(0), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_25_pcrel));
    break;
  case NDS32::JRAL:
    Bits = 0x4be00001 | (getReg(MI.getOperand(0)) << 10);
    break;
  case NDS32::JR:
    Bits = 0x4a000000 | (getReg(MI.getOperand(0)) << 10);
    break;
  // seb/seh/zeh: base 0x4000001{0,1,3} (op6=0x20, sub in Inst[9:0]). The old
  // 0x40008010 constant set a spurious bit 15 that corrupted the $ra field for
  // any source register other than $r1.
  case NDS32::SEB:
    Bits = 0x40000010 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15);
    break;
  case NDS32::SEH:
    Bits = 0x40000011 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15);
    break;
  case NDS32::ZEH:
    Bits = 0x40000013 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15);
    break;
  case NDS32::BEQZ:
    Bits = 0x4e020000 | (getReg(MI.getOperand(0)) << 20) |
           encodeBranchTarget(MI.getOperand(1), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_17_pcrel));
    break;
  case NDS32::BNEZ:
    Bits = 0x4e030000 | (getReg(MI.getOperand(0)) << 20) |
           encodeBranchTarget(MI.getOperand(1), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_17_pcrel));
    break;
  case NDS32::BEQ:
    Bits = 0x4c008000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           encodeBranchTarget(MI.getOperand(2), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_15_pcrel));
    break;
  case NDS32::BNE:
    Bits = 0x4c00c000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           encodeBranchTarget(MI.getOperand(2), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_15_pcrel));
    break;
  case NDS32::SUBrr:
    Bits = 0x40000001 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (getReg(MI.getOperand(2)) << 10);
    break;
  case NDS32::MULrr:
    Bits = 0x42000024 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (getReg(MI.getOperand(2)) << 10);
    break;
  case NDS32::DIVSR:
    Bits = 0x40000016 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(2)) << 15) |
           (getReg(MI.getOperand(3)) << 10) |
           (getReg(MI.getOperand(1)) << 5);
    break;
  case NDS32::DIVR:
    Bits = 0x40000017 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(2)) << 15) |
           (getReg(MI.getOperand(3)) << 10) |
           (getReg(MI.getOperand(1)) << 5);
    break;
  case NDS32::ANDrr:
    Bits = 0x40000002 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (getReg(MI.getOperand(2)) << 10);
    break;
  case NDS32::ORrr:
    Bits = 0x40000004 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (getReg(MI.getOperand(2)) << 10);
    break;
  case NDS32::XORrr:
    Bits = 0x40000003 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (getReg(MI.getOperand(2)) << 10);
    break;
  case NDS32::SLLrr:
    Bits = 0x4000000c | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (getReg(MI.getOperand(2)) << 10);
    break;
  case NDS32::SRLrr:
    Bits = 0x4000000d | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (getReg(MI.getOperand(2)) << 10);
    break;
  case NDS32::SRArr:
    Bits = 0x4000000e | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (getReg(MI.getOperand(2)) << 10);
    break;
  case NDS32::ANDri:
    Bits = 0x54000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getImm16(MI, MI.getOperand(2), Fixups, STI);
    break;
  case NDS32::ORri:
    Bits = 0x58000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getImm16(MI, MI.getOperand(2), Fixups, STI);
    break;
  case NDS32::XORri:
    Bits = 0x56000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getImm16(MI, MI.getOperand(2), Fixups, STI);
    break;
  case NDS32::SLLIri:
    Bits = 0x40000008 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           ((static_cast<uint32_t>(MI.getOperand(2).getImm()) & 0x1f) << 10);
    break;
  case NDS32::SRLIri:
    Bits = 0x40000009 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           ((static_cast<uint32_t>(MI.getOperand(2).getImm()) & 0x1f) << 10);
    break;
  case NDS32::SRAIri:
    Bits = 0x4000000a | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           ((static_cast<uint32_t>(MI.getOperand(2).getImm()) & 0x1f) << 10);
    break;
  case NDS32::SLT:
    Bits = 0x40000006 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (getReg(MI.getOperand(2)) << 10);
    break;
  case NDS32::SLTS:
    Bits = 0x40000007 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (getReg(MI.getOperand(2)) << 10);
    break;
  case NDS32::SLTI:
    Bits = 0x5c000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getImm16(MI, MI.getOperand(2), Fixups, STI);
    break;
  case NDS32::SLTSI:
    Bits = 0x5e000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getImm16(MI, MI.getOperand(2), Fixups, STI);
    break;
  case NDS32::BGEZ:
    Bits = 0x4e040000 | (getReg(MI.getOperand(0)) << 20) |
           encodeBranchTarget(MI.getOperand(1), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_17_pcrel));
    break;
  case NDS32::BLTZ:
    Bits = 0x4e050000 | (getReg(MI.getOperand(0)) << 20) |
           encodeBranchTarget(MI.getOperand(1), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_17_pcrel));
    break;
  case NDS32::BGTZ:
    Bits = 0x4e060000 | (getReg(MI.getOperand(0)) << 20) |
           encodeBranchTarget(MI.getOperand(1), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_17_pcrel));
    break;
  case NDS32::BLEZ:
    Bits = 0x4e070000 | (getReg(MI.getOperand(0)) << 20) |
           encodeBranchTarget(MI.getOperand(1), Fixups,
                              static_cast<MCFixupKind>(NDS32::fixup_nds32_17_pcrel));
    break;
  case NDS32::CLZ:
    Bits = 0x42000007 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15);
    break;
  case NDS32::WSBH:
    Bits = 0x40000014 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15);
    break;
  case NDS32::ROTRIri:
    Bits = 0x4000000b | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           ((static_cast<uint32_t>(MI.getOperand(2).getImm()) & 0x1f) << 10);
    break;
  // Conditional moves and MAC ops carry a tied $dstin in operand 1; the encoded
  // fields are dst (operand 0), src/a (operand 2), cond/b (operand 3).
  case NDS32::CMOVZ:
    Bits = 0x4000001a | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(2)) << 15) |
           (getReg(MI.getOperand(3)) << 10);
    break;
  case NDS32::CMOVN:
    Bits = 0x4000001b | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(2)) << 15) |
           (getReg(MI.getOperand(3)) << 10);
    break;
  case NDS32::MADDR32:
    Bits = 0x42000073 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(2)) << 15) |
           (getReg(MI.getOperand(3)) << 10);
    break;
  case NDS32::MSUBR32:
    Bits = 0x42000075 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(2)) << 15) |
           (getReg(MI.getOperand(3)) << 10);
    break;
  case NDS32::BITCI:
    Bits = 0x66000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (static_cast<uint32_t>(MI.getOperand(2).getImm()) & 0x7fff);
    break;
  // Register-offset memory: base + (index << scale). Operands for loads are
  // rt(0), base(1), index(2), scale(3); for stores rt(0) is the value with the
  // same base/index/scale ordering.
  case NDS32::LW_RR:
  case NDS32::LB_RR:
  case NDS32::LBS_RR:
  case NDS32::LH_RR:
  case NDS32::LHS_RR:
  case NDS32::SW_RR:
  case NDS32::SB_RR:
  case NDS32::SH_RR: {
    uint32_t Sub;
    switch (MI.getOpcode()) {
    case NDS32::LB_RR:  Sub = 0x00; break;
    case NDS32::LH_RR:  Sub = 0x01; break;
    case NDS32::LW_RR:  Sub = 0x02; break;
    case NDS32::LBS_RR: Sub = 0x10; break;
    case NDS32::LHS_RR: Sub = 0x11; break;
    case NDS32::SB_RR:  Sub = 0x08; break;
    case NDS32::SH_RR:  Sub = 0x09; break;
    default:            Sub = 0x0a; break; // SW_RR
    }
    uint32_t Scale = static_cast<uint32_t>(MI.getOperand(3).getImm()) & 0x3;
    Bits = 0x38000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           (getReg(MI.getOperand(2)) << 10) | (Scale << 8) | Sub;
    break;
  }
  // Post-increment loads: operands rt(0), ra_wb(1,tied), ra(2), imm(3); the
  // byte increment is scaled by the element size into a signed 15-bit field.
  case NDS32::LBI_POST:
  case NDS32::LBSI_POST:
  case NDS32::LHI_POST:
  case NDS32::LHSI_POST:
  case NDS32::LWI_POST: {
    uint32_t Op;
    int Shift;
    switch (MI.getOpcode()) {
    case NDS32::LBI_POST:  Op = 0x08000000; Shift = 0; break;
    case NDS32::LBSI_POST: Op = 0x28000000; Shift = 0; break;
    case NDS32::LHI_POST:  Op = 0x0a000000; Shift = 1; break;
    case NDS32::LHSI_POST: Op = 0x2a000000; Shift = 1; break;
    default:               Op = 0x0c000000; Shift = 2; break; // LWI_POST
    }
    int64_t Imm = MI.getOperand(3).getImm() >> Shift;
    Bits = Op | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(2)) << 15) |
           (static_cast<uint32_t>(Imm) & 0x7fff);
    break;
  }
  // Post-increment stores: operands ra_wb(0,tied), rt(1), ra(2), imm(3).
  case NDS32::SBI_POST:
  case NDS32::SHI_POST:
  case NDS32::SWI_POST: {
    uint32_t Op;
    int Shift;
    switch (MI.getOpcode()) {
    case NDS32::SBI_POST: Op = 0x18000000; Shift = 0; break;
    case NDS32::SHI_POST: Op = 0x1a000000; Shift = 1; break;
    default:              Op = 0x1c000000; Shift = 2; break; // SWI_POST
    }
    int64_t Imm = MI.getOperand(3).getImm() >> Shift;
    Bits = Op | (getReg(MI.getOperand(1)) << 20) |
           (getReg(MI.getOperand(2)) << 15) |
           (static_cast<uint32_t>(Imm) & 0x7fff);
    break;
  }
  // Single-precision FPU. Three-register ALU ops share the rt/ra/rb layout.
  case NDS32::FADDS:
  case NDS32::FSUBS:
  case NDS32::FMULS:
  case NDS32::FDIVS:
  case NDS32::FCPYSS:
  case NDS32::FCPYNSS:
  case NDS32::FCMPEQS:
  case NDS32::FCMPLTS:
  case NDS32::FCMPLES: {
    uint32_t Op;
    switch (MI.getOpcode()) {
    case NDS32::FADDS:   Op = 0x6a000000; break;
    case NDS32::FSUBS:   Op = 0x6a000040; break;
    case NDS32::FMULS:   Op = 0x6a000300; break;
    case NDS32::FDIVS:   Op = 0x6a000340; break;
    case NDS32::FCPYSS:  Op = 0x6a0000c0; break;
    case NDS32::FCPYNSS: Op = 0x6a000080; break;
    case NDS32::FCMPEQS: Op = 0x6a000004; break;
    case NDS32::FCMPLTS: Op = 0x6a000084; break;
    default:             Op = 0x6a000104; break; // FCMPLES
    }
    Bits = Op | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) | (getReg(MI.getOperand(2)) << 10);
    break;
  }
  // Two-register FPU ops: fd[24:20], fs1[19:15].
  case NDS32::FSQRTS:
  case NDS32::FABSS:
  case NDS32::FS2SI:
  case NDS32::FS2UI:
  case NDS32::FSI2S:
  case NDS32::FUI2S:
  case NDS32::FMFSR: {
    uint32_t Op;
    switch (MI.getOpcode()) {
    case NDS32::FSQRTS: Op = 0x6a0007c0; break;
    case NDS32::FABSS:  Op = 0x6a0017c0; break;
    case NDS32::FS2SI:  Op = 0x6a0063c0; break;
    case NDS32::FS2UI:  Op = 0x6a0043c0; break;
    case NDS32::FSI2S:  Op = 0x6a0033c0; break;
    case NDS32::FUI2S:  Op = 0x6a0023c0; break;
    default:            Op = 0x6a000001; break; // FMFSR (rt[24:20], fs[19:15])
    }
    Bits = Op | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15);
    break;
  }
  // fmtsr $rt, $fd: the GPR source is encoded in [24:20] and the FPR dest in
  // [19:15], but the instruction's operands are (FPR $fd, GPR $rt).
  case NDS32::FMTSR:
    Bits = 0x6a000009 | (getReg(MI.getOperand(1)) << 20) |
           (getReg(MI.getOperand(0)) << 15);
    break;
  case NDS32::FLSI:
    Bits = 0x30000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getMemOffsetWords(MI, MI.getOperand(2), Fixups, STI);
    break;
  case NDS32::FSSI:
    Bits = 0x32000000 | (getReg(MI.getOperand(0)) << 20) |
           (getReg(MI.getOperand(1)) << 15) |
           getMemOffsetWords(MI, MI.getOperand(2), Fixups, STI);
    break;
  default:
    report_fatal_error("NDS32 instruction encoding is not implemented");
  }

#ifndef NDEBUG
  // Migration guard: for instructions whose TableGen Inst{} fields are filled
  // in, the generated encoder must agree with the hand-written value above.
  {
    SmallVector<MCFixup, 4> TmpFixups;
    uint64_t Gen = getBinaryCodeForInstr(MI, TmpFixups, STI);
    assert((Gen == 0 || Gen == Bits) &&
           "TableGen Inst{} encoding disagrees with the hand-written encoder");
  }
#endif

  raw_svector_ostream OS(CB);
  support::endian::Writer Writer(
      OS, IsLittleEndian ? llvm::endianness::little : llvm::endianness::big);
  if (Size == 2)
    Writer.write<uint16_t>(static_cast<uint16_t>(Bits));
  else
    Writer.write<uint32_t>(Bits);
}

MCCodeEmitter *llvm::createNDS32MCCodeEmitter(const MCInstrInfo &MCII,
                                              MCContext &Ctx) {
  bool IsLittleEndian = Ctx.getTargetTriple().isLittleEndian();
  return new NDS32MCCodeEmitter(*Ctx.getRegisterInfo(), IsLittleEndian);
}
